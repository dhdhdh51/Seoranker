-- Site Audit tool: technical/on-page SEO crawl of a project's own (verified) website.
CREATE TABLE IF NOT EXISTS site_audits (
  id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  project_id     INT UNSIGNED NOT NULL,
  client_id      INT UNSIGNED NOT NULL,
  start_url      VARCHAR(2048) NOT NULL,
  host           VARCHAR(253) NOT NULL,
  status         ENUM('queued','running','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
  max_pages      INT UNSIGNED NOT NULL DEFAULT 100,
  max_depth      TINYINT UNSIGNED NOT NULL DEFAULT 4,
  pages_crawled  INT UNSIGNED NOT NULL DEFAULT 0,
  pages_found    INT UNSIGNED NOT NULL DEFAULT 0,
  score          TINYINT UNSIGNED NULL,
  error_count    INT UNSIGNED NOT NULL DEFAULT 0,
  warning_count  INT UNSIGNED NOT NULL DEFAULT 0,
  notice_count   INT UNSIGNED NOT NULL DEFAULT 0,
  site_checks    MEDIUMTEXT NULL,
  summary        MEDIUMTEXT NULL,
  error_message  VARCHAR(1000) NULL,
  created_by     INT UNSIGNED NULL,
  started_at     DATETIME NULL,
  finished_at    DATETIME NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_site_audits_project (project_id, created_at),
  KEY idx_site_audits_client (client_id),
  KEY idx_site_audits_status (status),
  CONSTRAINT fk_site_audits_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_site_audits_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE CASCADE,
  CONSTRAINT fk_site_audits_user FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS site_audit_pages (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  audit_id           INT UNSIGNED NOT NULL,
  url                VARCHAR(2048) NOT NULL,
  url_hash           CHAR(64) NOT NULL,
  depth              TINYINT UNSIGNED NOT NULL DEFAULT 0,
  found_on           VARCHAR(2048) NULL,
  in_sitemap         TINYINT(1) NOT NULL DEFAULT 0,
  status             ENUM('pending','done') NOT NULL DEFAULT 'pending',
  http_status        SMALLINT UNSIGNED NULL,
  final_url          VARCHAR(2048) NULL,
  redirect_count     TINYINT UNSIGNED NOT NULL DEFAULT 0,
  content_type       VARCHAR(120) NULL,
  is_html            TINYINT(1) NOT NULL DEFAULT 0,
  response_ms        INT UNSIGNED NULL,
  size_bytes         INT UNSIGNED NULL,
  title              VARCHAR(500) NULL,
  meta_description   TEXT NULL,
  h1                 VARCHAR(300) NULL,
  h1_count           SMALLINT UNSIGNED NULL,
  word_count         INT UNSIGNED NULL,
  canonical          VARCHAR(2048) NULL,
  robots_meta        VARCHAR(255) NULL,
  internal_links     INT UNSIGNED NULL,
  external_links     INT UNSIGNED NULL,
  images             INT UNSIGNED NULL,
  images_missing_alt INT UNSIGNED NULL,
  outlinks           MEDIUMTEXT NULL,
  issues             TEXT NULL,
  error              VARCHAR(500) NULL,
  fetched_at         DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_audit_page (audit_id, url_hash),
  KEY idx_audit_pages_pending (audit_id, status, depth),
  CONSTRAINT fk_audit_pages_audit FOREIGN KEY (audit_id) REFERENCES site_audits (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
